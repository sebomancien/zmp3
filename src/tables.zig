//! Constant tables of the MPEG-1 Layer III decoder (`zmp3.zig`), as
//! defined by ISO/IEC 11172-3 Annex B: the Huffman codes (table 3-B.7), the
//! scalefactor bands (table 3-B.8) and the synthesis window (table 3-B.3).
//! Only the tables that cannot be computed; the others are built at comptime
//! in `zmp3.zig`. The tests check that each Huffman code is complete and
//! prefix-free, and decode reference streams bit-accurately.

/// A Huffman code word: the first `len` bits of the stream (MSB first) equal
/// `code`. Big-value tables: the pair (`x`, `y`) (each 0..15, 15 meaning
/// "15 + linbits" in tables 16..31). Count1 tables: `x` = vwxy, `y` = 0.
pub const Code = struct { code: u32, len: u5, x: u4, y: u4 };

/// Big-value table `t` (0..31): its code words (empty for table 0, which
/// codes only zeros, and for the unused tables 4 and 14) and linbits.
