/// Count1 table B (`count1table_select` = 1): 4 bits, vwxy = 15 - code.
pub const tree_count1_b = blk: {
    var codes: [16]Code = undefined;
    for (&codes, 0..) |*c, i| c.* = .{ .code = i, .len = 4, .x = 15 - i, .y = 0 };
    break :blk codes;
};

